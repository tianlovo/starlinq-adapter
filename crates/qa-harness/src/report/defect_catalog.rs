//! QA 回归与实机缺陷台账（区分代码单元/桩回归与待实机复验状态）

use crate::models::DefectRecord;

macro_rules! define_defect_catalog {
    (
        $(
            {
                id: $id:expr,
                severity: $severity:expr,
                status: $status:expr,
                category: $category:expr,
                component: $component:expr,
                summary: $summary:expr,
                root_cause: $root_cause:expr,
                resolution: $resolution:expr,
                regression_test: $regression:expr $(,)?
            }
        ),* $(,)?
    ) => {
        /// 生成 QA 缺陷与实机缺陷审计记录列表（含范围限定状态，不可越级充当实机验收）
        pub fn known_defect_records() -> Vec<DefectRecord> {
            vec![
                $(
                    DefectRecord {
                        id: $id.to_string(),
                        severity: $severity.to_string(),
                        status: $status.to_string(),
                        category: $category.to_string(),
                        component: $component.to_string(),
                        summary: $summary.to_string(),
                        root_cause: $root_cause.to_string(),
                        resolution: $resolution.to_string(),
                        regression_test: $regression.to_string(),
                    },
                )*
            ]
        }
    };
}

