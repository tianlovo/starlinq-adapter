//! QQ 经典系统表情编号与中文名称双向静态映射表（声明式宏代码生成）

/// 批量生成 QQ 经典表情 ID 与中文名称双向查表函数
macro_rules! define_qq_faces {
    ($( $id:literal => $name:literal ),* $(,)?) => {
        /// 根据 OneBot `face` 消息段的数字编号查询对应 QQ 经典表情中文名称
        pub fn face_id_to_name(id: &str) -> Option<&'static str> {
            match id.trim() {
                $( $id => Some($name), )*
                _ => None,
            }
        }

        /// 根据 QQ 表情中文名称（支持 `[名称]`、`/名称` 与 `[表情:名称]`）反向查找 OneBot 表情数字编号
        pub fn face_name_to_id(raw_name: &str) -> Option<&'static str> {
            let trimmed = raw_name
                .trim()
                .trim_start_matches('/')
                .trim_start_matches('[')
                .trim_end_matches(']')
                .trim();
            let without_prefix = trimmed
                .strip_prefix("表情:")
                .or_else(|| trimmed.strip_prefix("表情："))
                .unwrap_or(trimmed)
                .trim();
            let normalized = without_prefix
                .trim_start_matches('/')
                .trim_start_matches('[')
                .trim_end_matches(']')
                .trim();
            if normalized.is_empty() {
                return None;
            }
            $(
                if normalized.eq_ignore_ascii_case($name) {
                    return Some($id);
                }
            )*
            None
        }
    };
}

